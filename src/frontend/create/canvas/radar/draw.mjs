import { drawCanvasRadar } from "../../../draw/canvas/radar.mjs";

export function createCanvasRadarDraw({
  context,
  canvas,
  targets,
  getTargetItems = () => targets.items(),
  location,
  elevationFeet = 0,
  state,
  windowRef,
  trails,
  airports,
  navaids,
  boundaries,
  ilsApproaches,
  procedures,
  airways,
  water = { paths: [], isVisible: () => false },
  legendTopInset = 0,
}) {
  return () =>
    drawCanvasRadar(
      context,
      canvas,
      getTargetItems(),
      location,
      state.range,
      state.offsetX,
      state.offsetY,
      windowRef,
      state.rotation,
      trails,
      state.connected,
      airports,
      navaids,
      boundaries,
      ilsApproaches,
      state.ilsVisible,
      procedures,
      { sidVisible: state.sidVisible, starVisible: state.starVisible },
      water.paths,
      water.isVisible(),
      elevationFeet,
      airways,
      state.airwayVisibility,
      {
        runwaysVisible: state.airportsVisible && state.runwaysVisible,
        extensionsVisible: state.airportsVisible && state.extensionsVisible,
        baseLegsVisible: state.airportsVisible && state.baseLegsVisible,
      },
      { airportsVisible: state.airportsVisible, navaidsVisible: state.navaidsVisible },
      legendTopInset,
    );
}

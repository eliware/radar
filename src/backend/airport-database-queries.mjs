const PAVED_SURFACES = "'ASPH', 'CONC', 'ASPH-CONC', 'CONC-ASPH', 'ASPH/CONC', 'CONC/ASPH'";

export const AIRPORT_QUERY = `SELECT A.ARPT_ID AS faaId, A.ICAO_ID AS icao, A.ARPT_NAME AS name,
  A.CITY AS city, A.STATE_CODE AS state, A.COUNTRY_CODE AS country,
  CAST(A.LAT_DECIMAL AS REAL) AS latitude, CAST(A.LONG_DECIMAL AS REAL) AS longitude,
  CAST(A.ELEV AS REAL) AS elevationFeet,
  COALESCE(C.CLASS_B_AIRSPACE, '') AS classB, COALESCE(C.CLASS_C_AIRSPACE, '') AS classC,
  COALESCE(C.CLASS_D_AIRSPACE, '') AS classD, COALESCE(C.CLASS_E_AIRSPACE, '') AS classE
  FROM APT_BASE A LEFT JOIN CLS_ARSP C ON A.ARPT_ID = C.ARPT_ID
  WHERE CAST(A.LAT_DECIMAL AS REAL) BETWEEN ? AND ?
  AND CAST(A.LONG_DECIMAL AS REAL) BETWEEN ? AND ?
  AND A.FACILITY_USE_CODE = 'PU'
  AND A.ICAO_ID GLOB 'K[A-Z0-9][A-Z0-9][A-Z0-9]'
  AND EXISTS (SELECT 1 FROM APT_RWY R WHERE R.ARPT_ID = A.ARPT_ID
    AND R.SURFACE_TYPE_CODE IN (${PAVED_SURFACES}) AND CAST(R.RWY_LEN AS REAL) > 1000)`;

export const RUNWAY_QUERY = `SELECT E.RWY_ID AS runwayId, E.RWY_END_ID AS endId,
  CAST(E.LAT_DECIMAL AS REAL) AS latitude, CAST(E.LONG_DECIMAL AS REAL) AS longitude,
  CAST(NULLIF(E.RWY_END_ELEV, '') AS REAL) AS elevationFeet,
  CAST(E.TRUE_ALIGNMENT AS REAL) AS alignmentDegrees FROM APT_RWY_END E
  JOIN APT_RWY R ON R.ARPT_ID = E.ARPT_ID AND R.RWY_ID = E.RWY_ID
  WHERE E.ARPT_ID = ? AND R.SURFACE_TYPE_CODE IN (${PAVED_SURFACES})
  AND CAST(R.RWY_LEN AS REAL) > 1000`;

export const NAVAID_QUERY = `SELECT NAV_ID AS identifier, NAV_TYPE AS type, NAME AS name,
  CITY AS city, STATE_CODE AS state, CAST(LAT_DECIMAL AS REAL) AS latitude,
  CAST(LONG_DECIMAL AS REAL) AS longitude, CAST(ELEV AS REAL) AS elevationFeet
  FROM NAV_BASE WHERE NAV_TYPE IN ('VOR', 'VOR/DME', 'VORTAC')
  AND CAST(LAT_DECIMAL AS REAL) BETWEEN ? AND ?
  AND CAST(LONG_DECIMAL AS REAL) BETWEEN ? AND ?`;

export const AIRWAY_QUERY = `SELECT S.AWY_ID AS name, S.AWY_LOCATION AS location,
  S.REGULATORY AS regulatory, CAST(S.POINT_SEQ AS INTEGER) AS sequence,
  S.FROM_POINT AS fix, S.TO_POINT AS nextFix,
  CAST(COALESCE(F.LAT_DECIMAL, N.LAT_DECIMAL) AS REAL) AS latitude,
  CAST(COALESCE(F.LONG_DECIMAL, N.LONG_DECIMAL) AS REAL) AS longitude
  FROM AWY_SEG_ALT S
  LEFT JOIN FIX_BASE F ON TRIM(S.FROM_PT_TYPE) IN ('WP', 'RP', 'CN')
    AND F.FIX_ID = S.FROM_POINT AND F.EFF_DATE = (SELECT MAX(EFF_DATE) FROM FIX_BASE)
    AND (S.ICAO_REGION_CODE = '' OR F.ICAO_REGION_CODE = S.ICAO_REGION_CODE)
    AND (S.STATE_CODE = '' OR F.STATE_CODE = S.STATE_CODE)
  LEFT JOIN NAV_BASE N ON TRIM(S.FROM_PT_TYPE) NOT IN ('WP', 'RP', 'CN')
    AND N.NAV_ID = S.FROM_POINT AND N.EFF_DATE = (SELECT MAX(EFF_DATE) FROM NAV_BASE)
    AND (S.STATE_CODE = '' OR N.STATE_CODE = S.STATE_CODE)
  WHERE S.EFF_DATE = (SELECT MAX(EFF_DATE) FROM AWY_SEG_ALT)
    AND SUBSTR(S.AWY_ID, 1, 1) IN ('Q', 'J', 'V')
  ORDER BY S.AWY_ID, S.AWY_LOCATION, S.REGULATORY, CAST(S.POINT_SEQ AS INTEGER)`;
